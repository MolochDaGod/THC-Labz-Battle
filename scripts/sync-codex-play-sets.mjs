/**
 * Dump Codex BadBudz + GrudaWars heroes into shared/codexPlaySets.generated.ts
 * Run from THC-Labz-Battle: node scripts/sync-codex-play-sets.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const sessionBad = 'C:/Users/nugye/.grok/sessions/C%3A%5CUsers%5Cnugye%5C01a09466-8b17-7d10-93da-37701504fd15/web_fetch/1.json';
const localCatalog = 'D:/Games/Models/_extract/rpg-maker-studio/dist/catalog/catalog.json';
const localBad = 'D:/Games/Models/_extract/rpg-maker-studio/dist/catalog/badbudz.json';

function loadJson(p) {
  if (!fs.existsSync(p)) return null;
  const raw = fs.readFileSync(p, 'utf8');
  try { return JSON.parse(raw); } catch { return null; }
}

async function fetchJson(url) {
  try {
    const r = await fetch(url, { headers: { 'user-agent': 'THC-Labz-Battle-codex-sync' } });
    if (!r.ok) return null;
    return await r.json();
  } catch {
    return null;
  }
}

const { mapCodexCatalogs, abilityIconFor, PLAY_STYLE_SLOTS } = await import('./map-codex-cjs.mjs');

let bad = await fetchJson('https://duelyst.grudge-studio.com/catalog/badbudz.json');
if (!bad) bad = loadJson(sessionBad);
if (!bad) bad = loadJson(localBad);
if (bad && !bad.cards && bad.id === 'badbudz') {
  /* already catalog shape */
} else if (bad && !bad.cards && typeof bad === 'object') {
  /* web_fetch wrapper? */
}

let cat = await fetchJson('https://duelyst.grudge-studio.com/catalog/catalog.json');
if (!cat) cat = loadJson(localCatalog);

if (!bad || !(bad.cards || bad.id)) {
  console.error('No badbudz catalog');
  process.exit(1);
}
if (!cat || !cat.heroes) {
  console.error('No catalog.json heroes');
  process.exit(1);
}

const mapped = mapCodexCatalogs(bad, cat);
const out = path.join(root, 'shared', 'codexPlaySets.generated.ts');
const header = `/* Generated by scripts/sync-codex-play-sets.mjs — Codex SSOT dump. Do not hand-edit. */\nimport type { ClassificationCard } from './classificationCardDatabase';\n\n`;
const body =
  header +
  `export const CODEX_BADBUDZ_CARDS: ClassificationCard[] = ${JSON.stringify(mapped.badbudz, null, 2)};\n\n` +
  `export const CODEX_GRUDAWARS_CARDS: ClassificationCard[] = ${JSON.stringify(mapped.grudawars, null, 2)};\n`;
fs.writeFileSync(out, body);
console.log('wrote', out, 'badbudz', mapped.badbudz.length, 'grudawars', mapped.grudawars.length);

const pveSrc = 'D:/Games/Models/THC_CARD_PACKS_OPTIONS/Cnftspriteasset/battle-cnft/production/city-pve.json';
const pveDestBattle = path.join(root, 'shared', 'city-pve.json');
const pveDestDope = 'F:/GitHub/Dope-Budz/client/src/budz-battle/data/city-pve.json';
if (fs.existsSync(pveSrc)) {
  fs.copyFileSync(pveSrc, pveDestBattle);
  fs.mkdirSync(path.dirname(pveDestDope), { recursive: true });
  fs.copyFileSync(pveSrc, pveDestDope);
  console.log('copied city-pve.json');
}

const defPath = 'F:/GitHub/Dope-Budz/client/src/budz-battle/data/card-definitions.json';
if (fs.existsSync(defPath) && fs.existsSync(pveSrc)) {
  const pve = JSON.parse(fs.readFileSync(pveSrc, 'utf8'));
  const defs = JSON.parse(fs.readFileSync(defPath, 'utf8'));
  const byId = new Map((defs.cards || []).map((c) => [c.id, c]));
  const rows = [];
  for (const city of pve.citiesRoster || []) {
    for (const row of [city.boss, ...(city.goons || [])]) {
      if (!row?.id) continue;
      rows.push(row);
    }
  }
  const seen = new Set();
  for (const row of rows) {
    if (seen.has(row.id)) continue;
    seen.add(row.id);
    const prev = byId.get(row.id) || {};
    const type = row.type === 'building' ? 'tower' : (row.type || prev.type || 'minion');
    byId.set(row.id, {
      ...prev,
      id: row.id,
      name: row.name || prev.name,
      image: row.image || prev.image,
      cost: row.cost ?? prev.cost,
      attack: row.attack ?? prev.attack,
      health: row.health ?? prev.health,
      rarity: row.rarity || prev.rarity,
      class: row.class || prev.class,
      type,
      description: prev.description || (row.abilities || []).join('. '),
      abilities: row.abilities || prev.abilities || [],
      abilityDesc: (row.abilities || []).join('. ') || prev.abilityDesc,
      traitRequirements: prev.traitRequirements || [],
      isNFTConnected: prev.isNFTConnected || false,
    });
  }
  defs.cards = [...byId.values()];
  fs.writeFileSync(defPath, JSON.stringify(defs, null, 2) + '\n');
  console.log('updated card-definitions.json', defs.cards.length);

  const pveCards = [];
  const seenPve = new Set();
  for (const city of pve.citiesRoster || []) {
    const push = (row, pveRole) => {
      if (!row?.id || seenPve.has(row.id)) return;
      seenPve.add(row.id);
      const cls = String(row.class || 'melee');
      const abilities = row.abilities || [];
      const playStyles = PLAY_STYLE_SLOTS.map((s) => ({
        key: s.key,
        on:
          (s.key === 'melee' && cls === 'melee') ||
          (s.key === 'ranged' && (cls === 'ranged' || cls === 'magical')) ||
          (s.key === 'splash' && cls === 'magical') ||
          (s.key === 'tank' && (cls === 'tank' || pveRole === 'boss')) ||
          (s.key === 'charge' && cls === 'melee' && pveRole === 'goon') ||
          false,
      }));
      const type = row.type === 'building' ? 'tower' : (row.type || 'minion');
      pveCards.push({
        id: row.id,
        name: row.name,
        image: row.image,
        cost: Number(row.cost ?? 3),
        attack: Number(row.attack ?? 0),
        health: Number(row.health ?? 0),
        description: abilities.join('. '),
        rarity: row.rarity || 'common',
        class: cls,
        type,
        abilities,
        abilityDesc: abilities.join('. '),
        traitRequirements: [],
        isNFTConnected: false,
        cardSet: 'clash',
        playStyles,
        keywords: abilities,
        artKind: 'portrait',
        statScale: 'clash',
        abilityIcons: abilities.map((n, i) => abilityIconFor(n, i, cls)),
        pveRole,
        city: city.city,
      });
    };
    if (city.boss) push(city.boss, 'boss');
    for (const g of city.goons || []) push(g, 'goon');
  }
  const pveOut = path.join(root, 'shared', 'cityPveCards.generated.ts');
  fs.writeFileSync(
    pveOut,
    `/* Generated from city-pve.json — THC Battle cards as city PVE challengers. Not Nemesis. */\nimport type { ClassificationCard } from './classificationCardDatabase';\n\nexport const CITY_PVE_CARDS: ClassificationCard[] = ${JSON.stringify(pveCards, null, 2)};\n`,
  );
  console.log('wrote', pveOut, pveCards.length);
}
